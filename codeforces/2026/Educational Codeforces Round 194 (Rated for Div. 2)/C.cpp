void solve() {
    int x, y; cin >> x >> y;
    int s = x + y;
    int op = 0;
    bool flag = false;
    for (int bit = 29; bit >= 0; --bit) {
        int bitS = (s >> bit) & 1;
        int bitX = (x >> bit) & 1;

        if (flag) {
            if (bitS == 1) op |= (1LL << bit);
        }
        else {
            if (bitS == 1 and bitX == 1) op |= (1LL << bit);
            else if (bitS == 0 and bitX == 1) flag = true;
        }
    }

    cout << s << ' ' << x - op << endl;
}

