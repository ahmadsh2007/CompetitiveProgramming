#include <bits/stdc++.h>
using namespace std;

#define str string

static const int IO_SPEEDUP = [](){
    ios::sync_with_stdio(false);
    cout.tie(nullptr);
    cin.tie(nullptr);
    return 0;
}();

void solve() {
    int n; cin >> n;
    str s = "";
    for (int i = 0; i < n; ++i) {
        s += "+--";
    }
    s += "+";
    cout << s << endl;

    int res; cin >> res;
    cout << n + (res + 2) / 3 << endl;
}

const int TESTCASES = 1;
signed main() {
    // print("Leeking"); // Yes, it works and yes, it's Python

    int TTT = 1;
    if (TESTCASES) cin >> TTT;
    while (TTT--) solve();
    return 0;
}